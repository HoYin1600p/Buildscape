    public static List<Removal> removals(String cluster) {
        return switch (cluster) {
            case "v118x" -> List.of();
            case "v121x" -> V121X;
            case "v26x" -> V26X;
            default -> throw new IllegalArgumentException("Unknown VersionCluster: " + cluster);
        };
    }

    public static boolean removes(String cluster, String path) {
        String id = path.contains(":") ? path : "buildscape:" + path;
        return removals(cluster).stream().anyMatch(removal -> removal.id().equals(id));
    }
